  // ── ACTIONS: VOYAGE ──────────────────────────────────────────────────────
  async function startVoyage(){
    if (!state.routeLegs.length){ setStatus('Plan an itinerary or add at least one stop first.', 'warn'); return; }
    if (state.voyage){
      const pending = unpostedSettlementItems(state.voyage);
      const pendGp = pending.reduce((s,a) => s + Math.max(0, Number(a.amountGp || 0)), 0);
      const pendTxt = pending.length
        ? ` It has ${pending.length} unposted settlement item${pending.length===1?'':'s'} (${pendGp} gp) — post them in the Voyage Ledger first, or they are archived unposted.`
        : '';
      if (!state.voyage.finished){
        if (!(await confirmDialog('Replace active voyage',
          `A voyage is already underway (${voyageRouteLabel(state.voyage)}). Starting a new one archives it as-is.${pendTxt}`,
          { okText:'Start New Voyage', danger:true }))) return;
      } else if (pending.length){
        // Finished voyage still holding unposted arrival settlement —
        // previously this was stomped with no confirm at all.
        if (!(await confirmDialog('Unsettled voyage',
          `The completed voyage (${voyageRouteLabel(state.voyage)}) still has unposted settlement.${pendTxt}`,
          { okText:'Start Anyway', danger:true }))) return;
      }
      archiveVoyage(state.voyage, 'replaced');
    }
    const p = state.panelEl;
    const shipId = p.querySelector('#ve-ship').value;
    const shipTpl = SHIP_TEMPLATES.find(s => s.id===shipId) || SHIP_TEMPLATES[0];
    const hullMax   = parseInt(p.querySelector('#ve-hull').value,10)  || shipTpl.hull;
    const dailySail = parseInt(p.querySelector('#ve-speed').value,10) || shipTpl.dailySail;
    const crew      = p.querySelector('#ve-crew').value || 'average';
    const quality   = SHIP_QUALITY[p.querySelector('#ve-quality')?.value] ? p.querySelector('#ve-quality').value : 'average';
    const navSkill  = parseInt(p.querySelector('#ve-nav').value,10)   || 12;
    const smuggleSkill = parseInt(p.querySelector('#ve-smuggle')?.value,10) || 4;
    const sd = parseInt(p.querySelector('#ve-sday').value,10)    || 1;
    const sm = parseInt(p.querySelector('#ve-smonth').value,10)  || 0;
    const sy = parseInt(p.querySelector('#ve-syear').value,10)   || 576;

    let cum = 0;
    // Recompute water paths in case the user painted more water since adding
    // legs. Measured/estimated distances refresh from the new path; manual
    // distances are never touched.
    state.routeLegs.forEach(leg => {
      const fh = portHex(leg.from), th = portHex(leg.to);
      if (fh && th){
        leg.path = findWaterPath(fh, th);
        if (leg.distanceSource !== 'manual'){
          if (leg.path && leg.path.length > 1){
            leg.distance = (leg.path.length - 1) * MILES_PER_HEX;
            leg.distanceSource = 'path';
          } else if (!Number(leg.distance)){
            leg.distance = Math.max(MILES_PER_HEX, Math.round(hexDistance(fh, th) * MILES_PER_HEX));
            leg.distanceSource = 'estimate';
          }
        }
      }
    });
    const legs = state.routeLegs.map(l => { cum += l.distance; return { ...l, cumDist:cum }; });

    const startCalendar = { day:sd, month:sm, year:sy };
    state.voyage = {
      captain: p.querySelector('#ve-capt').value || 'Captain',
      shipId,
      shipType: shipTpl.name,
      hullMax, hullCurrent: hullMax,
      dailySail,
      dailyOar: Number(shipTpl.dailyOar || 0),
      crewQuality: crew,
      crewMod: CREW_QUALITY_MOD[crew] ?? 0,
      quality,
      brokenMast: false,
      leaking: false,
      alerts: [],
      navSkill,
      smuggleSkill,
      calendar: { ...startCalendar },
      startCalendar,
      startDate: formatDate(startCalendar),
      currentDate: formatDate(startCalendar),
      arrivalDate: '',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      legs,
      totalDistance: cum,
      distanceCovered: 0,
      currentLegIdx: 0,
      milesOnLeg: 0,
      dayNumber: 0,
      finished: false,
      shipSank: false,
      endedAtPort: '',
      log: [],
      hexTrail: [],
      hullDamageTaken: 0,
      settlement: { pending:[], posted:[], notes:[], repairGpPerHull:REPAIR_GP_PER_HULL },
    };
    updateVoyageLocation('voyage-started');
    setStatus(`Voyage started — ${state.voyage.shipType} sailing ${legs[0].from} → ${legs[legs.length-1].to}.`);
    setActiveTab('voyage');
    renderShip();
    renderRouteOverlay();
    emitVoyageChanged('voyage-started');
  }

