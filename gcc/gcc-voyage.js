  // Port progress strip: node dots at leg boundaries, fill to the ship's
  // cumulative position, ship glyph, ETA to the next port at effective speed.
  function portStripHTML(v){
    const total = Math.max(1, Number(v.totalDistance || 0));
    const covered = Math.min(total, Math.max(0, Number(v.distanceCovered || 0)));
    const pct = d => Math.min(100, Math.max(0, (d/total)*100));
    let nodes = `<span class="node ${covered>0||v.finished?'done':''}" style="left:0%"></span>`;
    for (const leg of v.legs){
      nodes += `<span class="node ${covered >= leg.cumDist - 0.5 ? 'done' : ''}" style="left:${pct(leg.cumDist)}%"></span>`;
    }
    const shipPct = v.finished ? 100 : pct(covered);
    const leg = v.legs[v.currentLegIdx];
    let mid = '';
    if (!v.finished && leg){
      const cond = shipConditionMods(v);
      const eff = cond.deadInWater ? 0 : Math.max(1, Math.round(Number(v.dailySail||1)*cond.multiplier));
      const remain = Math.max(0, leg.distance - Number(v.milesOnLeg||0));
      const etaDays = cond.deadInWater ? null : Math.max(1, Math.ceil(remain/eff));
      const eta = etaDays == null ? 'ETA —' : `ETA ${esc(formatDate(calendarAdvance(v.calendar, etaDays)))}`;
      mid = `${esc(leg.to)} · ${Math.round(v.milesOnLeg)}/${leg.distance} mi · ${eta}`;
    } else if (v.finished){
      mid = v.endedAtPort && v.endedAtPort !== v.legs[v.legs.length-1]?.to ? `made port: ${esc(v.endedAtPort)}` : 'arrived';
    }
    return `
      <div class="ve-portstrip">
        <div class="track"></div><div class="fill" style="width:${shipPct}%"></div>
        ${nodes}
        <span class="shipglyph">⛵</span>
        <style>#voyage-panel .ve-portstrip .shipglyph{left:${shipPct}%}</style>
      </div>
      <div class="ve-portstrip-lbls">
        <span>${esc(v.legs[0]?.from || '')}</span>
        <span style="color:#c8a96e">${mid}</span>
        <span>${esc(v.legs[v.legs.length-1]?.to || '')}</span>
      </div>`;
  }

