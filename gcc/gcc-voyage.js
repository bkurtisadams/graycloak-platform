    // immediately (this was the "click hexes to show the path" ask).
    state.routeLegs.forEach(leg => {
      if (leg.from === name || leg.to === name){
        const fh = portHex(leg.from), th = portHex(leg.to);
        leg.path = (fh && th) ? findWaterPath(fh, th) : null;
      }
    });
