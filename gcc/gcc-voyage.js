  // ── ALERTS + FEED MIRROR ──────────────────────────────────────────────────
  // Critical events pin a banner in the helm until dismissed. Capped;
  // suppresses repeat unacked alerts of the same kind (dead-in-water days).
  function pushAlert(v, kind, text){
    if (!v) return;
    if (!Array.isArray(v.alerts)) v.alerts = [];
    if (v.alerts.some(a => !a.ack && a.kind === kind)) return;
    v.alerts.push({ id:uid('al'), kind, text, day:v.dayNumber, date:v.currentDate || dateObjToText(v.calendar), ack:false });
    if (v.alerts.length > 10) v.alerts = v.alerts.slice(-10);
  }
  const ALERT_EVENT_MATCHERS = [
    { kind:'capsize',   re:/CAPSIZES/ },
    { kind:'sank',      re:/Ship sank/ },
    { kind:'mast',      re:/mast snaps/ },
    { kind:'leak',      re:/beams take on water|she is LEAKING/i },
    { kind:'dead',      re:/Dead in the water/ },
    { kind:'arrival',   re:/^Arrived at |Voyage complete!/ },
    { kind:'madeport',  re:/Made port at |Came about and returned/ },
  ];
  function harvestAlerts(v, events){
    for (const e of events){
      const m = ALERT_EVENT_MATCHERS.find(x => x.re.test(e.text));
      if (m) pushAlert(v, m.kind, e.text);
    }
  }
